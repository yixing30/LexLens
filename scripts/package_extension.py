"""Build an unpacked Chrome extension folder for local installation."""

import json
import math
import shutil
import struct
import zlib
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "dist" / "LexLens-Chrome"
FILES = [
    "manifest.json",
    "src/background.js", "src/content.css", "src/content.js", "src/core.js",
    "src/options.html", "src/options.js", "src/popup.html", "src/popup.js", "src/selftest.html", "src/ui.css",
    "data/english-levels.js", "data/english-inline.js", "data/english-auto.js", "data/english-lookup.json", "data/english-detail.json",
    "data/ECDICT-LICENSE.txt", "data/NOTICE.md", "data/ENGLISH-LEVELS-NOTICE.md",
    "icons/icon-16.png", "icons/icon-32.png", "icons/icon-48.png", "icons/icon-128.png",
]


def png_chunk(kind: bytes, payload: bytes) -> bytes:
    return struct.pack(">I", len(payload)) + kind + payload + struct.pack(">I", zlib.crc32(kind + payload) & 0xFFFFFFFF)


def in_round_rect(x: float, y: float) -> bool:
    left, top, right, bottom, radius = 0.03, 0.03, 0.97, 0.97, 0.19
    cx = min(max(x, left + radius), right - radius)
    cy = min(max(y, top + radius), bottom - radius)
    return (x - cx) ** 2 + (y - cy) ** 2 <= radius ** 2


def color_at(x: float, y: float):
    if not in_round_rect(x, y):
        return (0, 0, 0, 0)
    background = (23, 58, 105, 255)
    white = (250, 253, 255, 255)
    aqua = (94, 226, 210, 255)
    if 0.22 < x < 0.32 and 0.20 < y < 0.78:
        return white
    if 0.22 < x < 0.62 and 0.67 < y < 0.78:
        return white
    distance = math.hypot(x - 0.62, y - 0.40)
    if 0.16 < distance < 0.22:
        return aqua
    if 0.70 < x < 0.87 and abs((y - 0.57) - (x - 0.70)) < 0.045:
        return aqua
    return background


def write_icon(size: int) -> None:
    rows = bytearray()
    for y in range(size):
        rows.append(0)
        for x in range(size):
            samples = [color_at((x + dx) / size, (y + dy) / size)
                       for dy in (0.125, 0.375, 0.625, 0.875)
                       for dx in (0.125, 0.375, 0.625, 0.875)]
            rows.extend(round(sum(sample[channel] for sample in samples) / 16) for channel in range(4))
    header = struct.pack(">IIBBBBB", size, size, 8, 6, 0, 0, 0)
    png = b"\x89PNG\r\n\x1a\n" + png_chunk(b"IHDR", header) + png_chunk(b"IDAT", zlib.compress(bytes(rows), 9)) + png_chunk(b"IEND", b"")
    path = ROOT / "icons" / f"icon-{size}.png"
    path.parent.mkdir(exist_ok=True)
    path.write_bytes(png)


def main() -> None:
    for size in (16, 32, 48, 128):
        write_icon(size)
    manifest = json.loads((ROOT / "manifest.json").read_text(encoding="utf-8"))
    assert manifest["manifest_version"] == 3
    for relative in FILES:
        if not (ROOT / relative).is_file():
            raise SystemExit(f"Missing extension asset: {relative}")
    marker = OUTPUT / ".lexlens-generated"
    if OUTPUT.exists():
        if not marker.exists():
            raise SystemExit(f"Refusing to replace an unrecognized folder: {OUTPUT}")
        shutil.rmtree(OUTPUT)
    for relative in FILES:
        destination = OUTPUT / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(ROOT / relative, destination)
    marker.write_text("Generated by scripts/package_extension.py\n", encoding="utf-8")
    (OUTPUT / "安装说明.txt").write_text(
        "LexLens 本地安装（Chrome 桌面版）\n"
        f"本机安装目录：{OUTPUT}\n"
        "1. 在 Chrome 地址栏输入 chrome://extensions 并回车。\n"
        "2. 打开右上角「开发者模式」。\n"
        "3. 点击左上角「加载已解压的扩展程序」。\n"
        "4. macOS 文件选择窗口可按 Command+Shift+G，粘贴上面的本机安装目录，再选择整个 LexLens-Chrome 文件夹。\n"
        "   不要选择里面的 manifest.json，也不用去 Chrome 网上应用店搜索。\n"
        "5. 在扩展菜单（拼图图标）中找到 LexLens 并固定，刷新已有网页。\n"
        "6. 在 Google Chrome 的网页标签中点击 LexLens 图标，查看面板顶部的当前网页状态。\n"
        "   英语默认按词表等级筛选，并在生词上方显示本地中文词典常见义。\n"
        "   面板可切换 A1–C2；「包含粗略估计」会增加按词频推测的生词释义。\n"
        "   也可点「打开标注自检页」；默认 B1 设置下，这一页应有多处上方释义。\n"
        "   点击图标也会尝试用当前页临时权限启动标注。若仍显示「未检测到 LexLens」，请在 chrome://extensions 的 LexLens 详情中检查网站访问权限，然后刷新网页。\n"
        "   Codex 应用的内置浏览器不会运行 Chrome 扩展。\n"
        "更新：重新运行 npm run build:extension，在扩展管理页点击 LexLens 的刷新图标，再刷新网页。\n",
        encoding="utf-8",
    )
    print(f"Install folder: {OUTPUT}")
    print(f"Files: {len(FILES)}; Version: {manifest['version']}")


if __name__ == "__main__":
    main()
